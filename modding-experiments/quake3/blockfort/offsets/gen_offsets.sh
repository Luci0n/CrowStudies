#!/bin/sh
# gen_offsets.sh <OpenArena gamecode checkout> > q3offsets.h
# gentity_t field offsets as the 32-bit QVM lays them out, from OpenArena's GPL headers.
set -e
HERE=$(cd "$(dirname "$0")" && pwd); T=$(mktemp -d)
printf '#define __LITTLE_ENDIAN 1234\n#define __BIG_ENDIAN 4321\n#define __BYTE_ORDER __LITTLE_ENDIAN\n' > "$T/endian.h"
echo "/* generated by offsets/gen_offsets.sh from OpenArena gamecode headers (gcc -m32 -DQ3_VM) */"
gcc -m32 -DQ3_VM -ffreestanding -nostdinc -w -S -o - -I"$T" -I"$1/code/game" "$HERE/off.c" | python3 -c '
import sys, re
name = None
for l in sys.stdin:
    m = re.match(r"^(\w+):$", l)
    if m: name = m.group(1); continue
    m = re.match(r"^\s+\.(long|zero)\s+(-?\d+)", l)
    if m and name:
        print("#define %s %s" % (name, m.group(2) if m.group(1) == "long" else 0)); name = None'
