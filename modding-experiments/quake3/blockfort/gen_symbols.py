#!/usr/bin/env python3
"""re.json (qvm_re.py output) + the QVM -> re_symbols.h for blockfort.c, and the --hook flags."""
import json, sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from qvm_re import QVM

qvm, header, rej, out = sys.argv[1:5]
q = QVM(qvm, header)
f = json.load(open(rej))["found"]
need = ["G_Spawn", "G_FreeEntity", "G_Damage", "G_RadiusDamage", "G_RunFrame", "g_entities", "sizeof(gentity_t)"]
missing = [n for n in need if n not in f]
if missing:
    sys.exit("RE did not find: %s" % missing)
lit = q.lit.find(b"\0func_static\0")
sysno = {v: k for k, v in q.sys.items()}
with open(out, "w") as o:
    o.write("/* generated by gen_symbols.py from qvm_re.py's identifications */\n")
    for n in ("G_Spawn", "G_FreeEntity", "G_Damage", "G_RadiusDamage"):
        o.write("int f_%d(int ps);\n#define F_%s f_%d\n" % (f[n], n, f[n]))
    o.write("#define G_ENTITIES %d\n" % f["g_entities"])
    o.write("#define RE_SIZEOF_GENTITY %d\n" % f["sizeof(gentity_t)"])
    o.write("#define LIT_FUNC_STATIC %d\n" % (q.dlen + lit + 1))
    o.write("#define SYS_G_LINKENTITY %d\n" % sysno["G_LINKENTITY"])
    o.write("#define SYS_G_POINT_CONTENTS %d\n" % sysno["G_POINT_CONTENTS"])
    o.write("int bf_runframe(int ps, int (*orig)(int));\nint bf_radius(int ps, int (*orig)(int));\n")
print("--hook %d=bf_runframe --hook %d=bf_radius" % (f["G_RunFrame"], f["G_RadiusDamage"]))
